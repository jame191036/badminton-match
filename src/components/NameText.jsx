// ชื่อผู้เล่นที่ตัดบรรทัดได้เฉพาะตรงช่องว่าง — "ศุภวิชญ์ (ต้นข้าว)" ขึ้นบรรทัดใหม่ที่ "(ต้นข้าว)"
// ไม่ใช่กลาง "ต้น|ข้าว": ตัวตัดคำไทยของเบราว์เซอร์มองว่าเป็นสองคำ และ word-break: keep-all
// ไม่มีผลกับภาษาไทยใน Chrome · ช่องว่างอยู่นอก .nm-part จึงยังเป็นจุดตัดบรรทัดได้ตามปกติ
//
// ต้องห่อด้วย element อีกชั้นถ้าแม่เป็น flex — ไม่งั้นแต่ละส่วนกลายเป็น flex item
// แล้วช่องว่างหน้าส่วนที่สองจะถูกตัดทิ้ง ("ศุภวิชญ์(ต้นข้าว)")
export default function NameText({ name }) {
  return name.split(' ').map((part, i) => (
    <span key={i}>
      {i > 0 && ' '}
      <span className="nm-part">{part}</span>
    </span>
  ))
}
