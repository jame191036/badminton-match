-- ฝั่งแอป subscribe แบบมี filter เช่น session_id=eq.<id> เพื่อรับเฉพาะ
-- ความเปลี่ยนแปลงของวันเล่นที่เปิดอยู่
--
-- แต่ค่าเริ่มต้นของ Postgres (replica identity = default) ใส่มาให้แค่คีย์หลัก
-- ใน payload ของ DELETE — ไม่มี session_id ให้ filter เทียบ Supabase จึงทิ้ง
-- event นั้นไป ผลคือลบผู้เล่น/คอร์ต/เกม แล้วเครื่องอื่นไม่รู้จนกว่าจะรีเฟรช
--
-- replica identity full = ส่งค่าทุกคอลัมน์ของแถวที่ถูกลบมาด้วย filter จึงจับได้
-- แลกกับ WAL ที่ใหญ่ขึ้นเล็กน้อย ซึ่งไม่มีนัยกับขนาดข้อมูลของแอปนี้
--
-- (เครื่องที่กดลบเองเห็นผลทันทีอยู่แล้ว เพราะ useBadmintonData โหลดใหม่
--  หลังเขียนสำเร็จ ไม่ได้รอ realtime — ไฟล์นี้แก้เฉพาะฝั่งเครื่องอื่น)
-- ============================================================

